#!/usr/bin/env bash
set -euo pipefail

# Builds the vietasr DSP core to WebAssembly.
# The ONNX encoder runs separately via onnxruntime-web (see src/index.js).

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CORE="$HERE/../../core"
OUT="$HERE/dist"
mkdir -p "$OUT"

if ! command -v em++ >/dev/null 2>&1; then
    echo "em++ not found. Activate emsdk first:"
    echo "  source /path/to/emsdk/emsdk_env.sh"
    exit 1
fi

SOURCES=(
    "$HERE/src/wasm_api.cc"
    "$CORE/src/preprocess/kaldi_fbank.cc"
    "$CORE/src/preprocess/audio_resampler.cc"
    "$CORE/src/modules/vietasr/transducer_search.cc"
    "$CORE/src/modules/vietasr/post_processor.cc"
    "$CORE/src/modules/vietasr/units.cc"
)

EXPORTED_FUNCS='["_vietasr_wasm_init","_vietasr_wasm_vocab_size","_vietasr_wasm_feature_dim","_vietasr_wasm_reset","_vietasr_wasm_accept_pcm","_vietasr_wasm_pcm_length","_vietasr_wasm_pcm_ptr","_vietasr_wasm_compute_features","_vietasr_wasm_features_ptr","_vietasr_wasm_search_begin","_vietasr_wasm_search_pending","_vietasr_wasm_search_pending_ptr","_vietasr_wasm_search_accept_decoder","_vietasr_wasm_search_joiner_inputs","_vietasr_wasm_joiner_encoder_ptr","_vietasr_wasm_joiner_decoder_ptr","_vietasr_wasm_search_accept_logits","_vietasr_wasm_search_text","_malloc","_free"]'

em++ "${SOURCES[@]}" \
    -I"$CORE/include" \
    -I"$CORE/src" \
    -O3 \
    -msimd128 \
    -std=c++17 \
    -s WASM=1 \
    -s MODULARIZE=1 \
    -s EXPORT_ES6=1 \
    -s EXPORT_NAME=createVietasrModule \
    -s ALLOW_MEMORY_GROWTH=1 \
    -s EXPORTED_FUNCTIONS="$EXPORTED_FUNCS" \
    -s EXPORTED_RUNTIME_METHODS='["ccall","cwrap","HEAPF32","HEAP32","UTF8ToString","stringToUTF8","lengthBytesUTF8"]' \
    -o "$OUT/vietasr-core.js"

echo "built: $OUT/vietasr-core.js + $OUT/vietasr-core.wasm"
ls -lh "$OUT"/vietasr-core.*

# The ~78 MB int8 model is fetched at runtime from Hugging Face (kept out of the
# npm package), pinned to the revision in core/src/modules/vietasr/models.json.
node --input-type=module -e '
import { readFileSync, writeFileSync } from "node:fs";
const m = JSON.parse(readFileSync(process.argv[1], "utf8"));
const files = m.files.map(({ role, name, size, sha256 }) => ({ role, name, size, sha256 }));
writeFileSync(process.argv[2],
    "// Generated by build-wasm.sh from core/src/modules/vietasr/models.json — do not edit.\n" +
    `export const MODEL_BASE_URL = ${JSON.stringify(m.base_url)};\n` +
    `export const MODEL_FILES = ${JSON.stringify(files, null, 4)};\n`);
' "$CORE/src/modules/vietasr/models.json" "$OUT/model-config.js"
echo "model config -> $OUT/model-config.js"
